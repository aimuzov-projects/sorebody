const EMAIL = /[\p{L}\d._%+-]+@[\p{L}\d.-]+\.\p{L}{2,}/gu

// Российский номер в любой записи: +7 или 8, затем 10 цифр с пробелами, скобками и дефисами
const PHONE = /(?:\+7|(?<!\d)8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}(?!\d)/g

/** Почта и телефоны из реплики -- до того, как она уйдёт к модели: контакты чату не нужны. */
export function maskContacts(text: string) {
	return text.replace(EMAIL, '[почта скрыта]').replace(PHONE, '[телефон скрыт]')
}
