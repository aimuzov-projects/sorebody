/**
 * Слова, которые ничего не говорят о травме: "болит после прыжков на тумбу" ищется по "болит",
 * "прыжков" и "тумбу". Сравниваются после `normalize`.
 */
const STOP_WORDS = new Set(
	(
		'и в во на с со по к ко у о об от до за из не ни а но что как это после при для мне меня я мой моя ' +
		'ли же бы то или его ее их есть был была было были все очень когда где уже еще так там тут ' +
		'the a an of in on and or to with my is'
	).split(' '),
)

/**
 * Окончания, которые срезает `stem`, длинные раньше коротких. Грубо, без словаря:
 * "колено", "колени" и "коленом" сходятся в "колен", а "коленный" -- нет,
 * его ловит поиск по началу слова.
 *
 * Глаголов в вопросах много ("ударился", "тошнит"), их окончания тоже здесь.
 */
const ENDINGS = (
	'ями ами ией иям иях ого его ому ему ыми ими ость ости ой ей ий ый ая яя ое ее ые ие ую юю ам ям ах ях ' +
	'ом ем ов ев ию ия ии а я о е ы и у ю ь ить ать ять еть ит ет ут ют ат ят ил ел ал ял'
)
	.split(' ')
	.sort((a, b) => b.length - a.length)

/** Возвратная частица: "кружится" и "кружит" -- одно слово. */
const REFLEXIVE = /(?:ся|сь)$/

/** Короче основа становится неузнаваемой: "ног" ещё нога, "но" -- уже нет. */
const MIN_STEM = 3

const normalize = (word: string) => word.toLowerCase().replaceAll('ё', 'е')

/** Основа слова: без окончания, если после него остаётся хотя бы `MIN_STEM` букв. */
export function stem(word: string) {
	const base = word.length - 2 > MIN_STEM ? word.replace(REFLEXIVE, '') : word
	const ending = ENDINGS.find((e) => base.endsWith(e) && base.length - e.length >= MIN_STEM)

	return ending ? base.slice(0, -ending.length) : base
}

/** Основы слов текста в порядке появления, без служебных слов. Латиница и цифры тоже слова: ПКС, ACL, L5. */
export function terms(text: string) {
	return (normalize(text).match(/[\p{L}\p{N}]+/gu) ?? []).filter((w) => !STOP_WORDS.has(w)).map(stem)
}
