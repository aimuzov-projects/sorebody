/**
 * Слова кроссфита и зала, а также футбольный жаргон, которым не место в общей части травмы: её читает и бегун, и паделист,
 * спорт со своими движениями живёт в линзе. `(?<!\p{L})` -- начало слова, `\b` кириллицу не видит;
 * `\s` в JS ловит и неразрывный пробел, и перенос строки. «Толчок» не в списке: толчок стопой --
 * это и про ходьбу.
 */
const SPORT_WORDS = [
	/кроссфит/iu,
	/crossfit/iu,
	/(?<!\p{L})wod(?!\p{L})/iu,
	/(?<!\p{L})hift(?!\p{L})/iu,
	/функциональн\p{L}*\s+фитнес/iu,
	// Кроме «комплексного лечения», «комплекса упражнений» и анатомии запястья -- треугольного
	// фиброзно-хрящевого комплекса
	/(?<!\p{L})(?<!хрящев\p{L}*\s+)комплекс(?!н)(?!\p{L}*\s+упражнени)/iu,
	/(?<!\p{L})штанг/iu,
	/(?<!\p{L})гриф(?:а|у|ом|е|ы|ов)?(?!\p{L})/iu,
	/(?<!\p{L})турник/iu,
	/(?<!\p{L})перекладин/iu,
	// Гимнастические кольца: «на кольцах», «с кольцами». Просто «кольца» -- это и фиброзное кольцо
	// диска, и кольца на пальцах, которые снимают с отёкшей руки
	/(?<!\p{L})(?:на|с)\s+кольц\p{L}*|(?<!\p{L})кольцах(?!\p{L})/iu,
	/(?<!\p{L})тумб/iu,
	/(?<!\p{L})на\s+бокс/iu,
	// Рывок как упражнение; «резкий рывок руки» и «рывком» -- про механизм, их пропускаем
	/(?<!\p{L})(?<!резк\p{L}*\s+)рыв(?:ок|к(?!ом)\p{L}*)/iu,
	/(?<!\p{L})б(?:[её]|у)рпи/iu,
	/(?<!\p{L})трастер/iu,
	/(?<!\p{L})(?:спорт)?зал(?:е|а|у|ом|ы|ах|ов|ами)?(?!\p{L})/iu,
	/(?<!\p{L})раунд/iu,
	/(?<!\p{L})табло(?!\p{L})/iu,
	// Футбол: само слово в общей части встречается в сносках на исследования футболистов, а снаряжение
	// и игровые ситуации -- уже линза
	/(?<!\p{L})подкат/iu,
	/(?<!\p{L})бутс/iu,
	/(?<!\p{L})щитк/iu,
]

/** Найденные в тексте слова спорта, по одному на правило. */
export const sportWordsIn = (text: string) => SPORT_WORDS.flatMap((word) => text.match(word)?.[0] ?? [])
